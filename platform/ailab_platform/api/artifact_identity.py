"""Trusted source identity recovery, independent of user-visible collision names."""

from pathlib import PurePosixPath

from fastapi import HTTPException
from sqlalchemy import select

from ..models import Artifact, FileObject, Run
from .upload_identity import fingerprint


def output_key(value):
    if value is None:
        return None
    path = PurePosixPath(value)
    if (
        not value
        or path.is_absolute()
        or str(path) != value
        or any(p in {".", ".."} for p in value.split("/"))
        or "\\" in value
        or "\x00" in value
    ):
        raise HTTPException(422, "invalid output_key")
    return value


def legacy_filename(file, run_id):
    # This layout is generated by the API, never infer provenance by stripping numeric suffixes.
    if run_id is None:
        parts = file.storage_key.split("/", 3)
        run_id = parts[1] if len(parts) == 4 and parts[0] == "runs" and parts[2] == file.id else None
    prefix = f"runs/{run_id}/{file.id}/"
    key = file.storage_key
    name = key[len(prefix) :] if key.startswith(prefix) else ""
    return name if name and PurePosixPath(name).name == name and name not in {".", ".."} else None


def repair_metadata(db, file):
    if (file.meta or {}).get("artifact_filename"):
        return False
    parts = file.storage_key.split("/", 3)
    origin = (file.meta or {}).get("run_id") or (parts[1] if len(parts) == 4 and parts[0] == "runs" and parts[2] == file.id else None)
    association = db.scalar(
        select(Artifact.id)
        .join(Run, Run.id == Artifact.run_id)
        .where(Artifact.file_id == file.id, Artifact.run_id == origin, Run.user_id == file.user_id)
        .limit(1)
    )
    if not origin or association is None:
        return False
    name = legacy_filename(file, origin)
    if not name:
        return False
    file.meta = {**(file.meta or {}), "artifact_filename": name}
    return True


def request_fingerprint(body):
    return fingerprint(
        filename=body.filename,
        output_key=body.output_key,
        sha256=body.sha256,
        size=body.size,
        content_type=body.content_type,
        role=body.role,
    )


def verify_replay(db, prior, body):
    digest = request_fingerprint(body)
    if prior.fingerprint is None:
        file = db.get(FileObject, prior.result.get("file_id"))
        name = (file.meta or {}).get("artifact_filename") or legacy_filename(file, body.run_id) if file else None
        if (
            file is None
            or (file.sha256, file.size, file.content_type, name, prior.result.get("role"))
            != (body.sha256, body.size, body.content_type, body.filename, body.role)
            or body.output_key is not None
        ):
            raise HTTPException(422, "旧交付收据无法确认此请求，请使用新的交付标识")
        prior.fingerprint = digest
    if prior.fingerprint != digest:
        raise HTTPException(422, "交付标识已用于其他内容")
    file = db.get(FileObject, prior.result.get("file_id"))
    if file is None or file.deleted_at is not None or file.purged_at is not None:
        raise HTTPException(410, "已交付文件已删除")
