"""Desired resource ownership. Live records never expire before confirmed deletion."""

from typing import Protocol

LIVE_STATES = frozenset({"creating", "active", "releasing"})
LEASE_STATES = ("creating", "active", "releasing", "released", "failed")


class LeaseStore(Protocol):
    def get(self, lease_id: str) -> dict | None: ...
    def all(self) -> list[dict]: ...
    def live(self) -> list[dict]: ...
    def cas(self, lease_id: str, version: int | None, record: dict) -> bool:
        """Insert if absent (None), otherwise replace exactly this version; increment version."""
        ...

    def delete(self, lease_id: str, version: int) -> bool: ...
    def claim_owner(self, token: str, ttl: int) -> bool:
        """Claim an empty owner lock or extend our own lock, atomically."""
        ...

    def owns(self, token: str) -> bool: ...
    def release_owner(self, token: str) -> None: ...
