"""Bounded object storage port; callers own streams and close them in finally."""

from collections.abc import Iterable, Iterator
from contextlib import AbstractContextManager
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import BinaryIO, Protocol


@dataclass(frozen=True)
class ObjectInfo:
    size: int
    etag: str
    content_type: str


@dataclass(frozen=True)
class StoredObject:
    key: str
    size: int
    modified_at: datetime


@dataclass(frozen=True)
class ObjectPage:
    items: list[StoredObject]
    cursor: str | None = None

    def __iter__(self) -> Iterator[StoredObject]:
        return iter(self.items)


class Storage(Protocol):
    def put_stream(
        self, key: str, source: Iterable[bytes] | BinaryIO, content_type: str = "application/octet-stream", *, max_bytes: int
    ) -> None: ...
    def open_stream(self, key: str, chunk_size: int = 65536) -> AbstractContextManager[Iterator[bytes]]: ...
    def stream(self, key: str, chunk_size: int = 65536) -> Iterator[bytes]: ...
    def info(self, key: str) -> ObjectInfo: ...
    def list_prefix(self, prefix: str, cursor: str | None = None, limit: int = 1000) -> ObjectPage: ...
    def copy(self, src_key: str, dst_key: str) -> None: ...
    def delete_prefix(self, prefix: str) -> int: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...
    def put_bytes(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None: ...
    def get_bytes(self, key: str) -> bytes: ...
    def put_file(self, key: str, path: str | Path, content_type: str = "application/octet-stream") -> None: ...
    def size(self, key: str) -> int: ...
    def commit(self, staging_key: str, final_key: str) -> None: ...
    def presign_put(self, key: str, expires: int = 900) -> str | None: ...
    def presign_get(self, key: str, expires: int = 900) -> str | None: ...
